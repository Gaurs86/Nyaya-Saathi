"""Generate printable PDF samples from the synthetic benchmark for manual app testing.

Outputs are local-only under evals/generated by default and should not be committed.
"""
from __future__ import annotations

import argparse
import json
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATASET = ROOT / "evals" / "fixtures" / "benchmark.json"
DEFAULT_OUTPUT = ROOT / "evals" / "generated"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--dataset", type=Path, default=DATASET)
    args = parser.parse_args(argv)

    try:
        from reportlab.lib import colors
        from reportlab.lib.pagesizes import letter
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib.units import inch
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
    except ImportError:
        parser.error("ReportLab is required. Install it with: python -m pip install reportlab")

    try:
        dataset = json.loads(args.dataset.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        parser.error(f"Could not read benchmark dataset: {exc}")

    args.output_dir.mkdir(parents=True, exist_ok=True)
    styles = getSampleStyleSheet()
    body = ParagraphStyle(
        "SyntheticNoticeBody",
        parent=styles["BodyText"],
        fontName="Helvetica",
        fontSize=10.5,
        leading=15,
        spaceAfter=7,
    )
    heading = ParagraphStyle(
        "SyntheticNoticeHeading",
        parent=styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=14,
        leading=18,
        textColor=colors.HexColor("#333333"),
        spaceAfter=14,
    )

    def page_chrome(canvas, doc):
        canvas.saveState()
        canvas.setFillColor(colors.HexColor("#8B1E1E"))
        canvas.setFont("Helvetica-Bold", 8)
        canvas.drawString(doc.leftMargin, letter[1] - 0.42 * inch, "SYNTHETIC TEST SAMPLE - NOT A REAL LEGAL NOTICE")
        canvas.setFillColor(colors.grey)
        canvas.setFont("Helvetica", 8)
        canvas.drawRightString(letter[0] - doc.rightMargin, 0.35 * inch, f"Software evaluation fixture | Page {doc.page}")
        canvas.restoreState()

    count = 0
    for case in dataset.get("cases", []):
        case_id = case["case_id"]
        target = args.output_dir / f"{case_id}.pdf"
        document = SimpleDocTemplate(
            str(target),
            pagesize=letter,
            rightMargin=0.8 * inch,
            leftMargin=0.8 * inch,
            topMargin=0.8 * inch,
            bottomMargin=0.65 * inch,
            title=f"Synthetic test fixture - {case_id}",
            author="Nyaya-Saathi evaluation harness",
        )
        story = [
            Paragraph(f"Synthetic test fixture: {escape(case_id)}", heading),
            Paragraph("Fictional sample content for software testing only. Do not use as a real notice or legal template.", body),
            Spacer(1, 4),
        ]
        for line in str(case.get("notice_text", "")).splitlines():
            if line.strip():
                story.append(Paragraph(escape(line), body))
            else:
                story.append(Spacer(1, 5))
        document.build(story, onFirstPage=page_chrome, onLaterPages=page_chrome)
        print(f"Generated {target}")
        count += 1

    print(f"Generated {count} synthetic PDFs. These files are local test data, not legal templates.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
